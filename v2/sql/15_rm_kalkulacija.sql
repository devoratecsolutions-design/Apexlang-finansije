  left join operacije o on o.id = ks.operacija_id;

-- izvori raspodjele (fakture i zavisni troškovi) sa stanjem raspodjele
create or replace force view vw_rm_kalkulacija_izvori as
select 'F:' || kk.id                                                    as izvor,
       kk.kalkulacija_id,
       kk.id                                                            as kalkulacija_kuf_id,
       cast(null as number)                                             as kalkulacija_trosak_id,
       'Faktura'                                                        as vrsta,
       k.naziv || ' · ' || kl.naziv                                     as naziv,
       kk.iznos,
       nvl(kk.nacin_raspodjele, 'V')                                    as nacin,
       (select nvl(sum(r.iznos), 0) from kalkulacija_raspodjela r where r.kalkulacija_kuf_id = kk.id) as rasporedjeno,
       rm_kalkulacija_pkg.izvor_rasporedjen(kk.id, null)                 as rasporedjen,
       kk.id                                                            as redoslijed
  from kalkulacija_kuf kk
  join kuf k on k.id = kk.kuf_id
  left join sec_klijenti kl on kl.id = k.klijent_id
union all
select 'T:' || t.id,
       t.kalkulacija_id,
       null,
       t.id,
       'Zavisni trošak',
       t.opis,
       t.iznos,
       nvl(t.nacin_raspodjele, 'V'),
       (select nvl(sum(r.iznos), 0) from kalkulacija_raspodjela r where r.kalkulacija_trosak_id = t.id),
       rm_kalkulacija_pkg.izvor_rasporedjen(null, t.id),
       1000000000 + t.id
  from kalkulacija_troskovi t;

-- raspodjela po stavkama sa nazivom izvora
create or replace force view vw_rm_kalkulacija_raspodjela as
select r.id,
       r.kalkulacija_id,
       case when r.kalkulacija_kuf_id is not null then 'F:' || r.kalkulacija_kuf_id else 'T:' || r.kalkulacija_trosak_id end as izvor,
       r.kalkulacija_stavka_id,
       s.prijemnica,
       s.sifra,
       s.naziv,
       s.kolicina,
       s.osnovica,
       r.iznos,
       case when nvl(s.kolicina, 0) = 0 or r.iznos is null then null else round(r.iznos / s.kolicina, 6) end as cijena
  from kalkulacija_raspodjela r
  join vw_rm_kalkulacija_stavke s on s.id = r.kalkulacija_stavka_id;

