-- brojač KALK (tekuća godina) za firme koje imaju vrstu dokumenta KALK
declare
    l_modul number;
    l_novih number := 0;
begin
    select id into l_modul from sif.acc_moduli where upper(sifra) = 'MAT';
    for v in (select vd.id, vd.ooj_id from sif.vrste_dokumenata vd
               where vd.acc_modul_id = l_modul and upper(vd.sifra) = 'KALK' and vd.ooj_id is not null and vd.valid = 'Y') loop
        if not core.protokoli_pkg.check_brojac(v.ooj_id, 'kalk', extract(year from sysdate)) then
            core.protokoli_pkg.insert_protokol(v.ooj_id, v.id, extract(year from sysdate), 'KALK-', 0, null, 6, 'Y');
            l_novih := l_novih + 1;
        end if;
    end loop;
    commit;
    dbms_output.put_line('Novi brojači KALK: ' || l_novih);
end;
