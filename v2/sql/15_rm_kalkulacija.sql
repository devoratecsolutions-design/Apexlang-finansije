-- 3) view-ovi -------------------------------------------------------------------------
create or replace force view vw_rm_kalkulacije as
select k.id,
       k.ooj_id,
       k.godina,
       k.broj,
       k.naziv,
       k.datum,
       k.opis,
       k.skladiste_id,
       s.sifra || ' - ' || s.naziv                                       as skladiste,
       case when upper(ts.sifra) = 'ROB' then 'Y' else 'N' end            as robno,
       nvl(k.status, case when k.zakljucano = 'Y' then 'Z' else 'P' end)  as status,
       nvl(k.nacin_raspodjele, 'V')                                      as nacin_raspodjele,
       (select listagg(o.naziv, ', ') within group (order by o.datum, o.id)
          from kalkulacija_operacije ko join operacije o on o.id = ko.operacija_id
         where ko.kalkulacija_id = k.id)                                 as prijemnice,
       (select count(*) from kalkulacija_operacije ko where ko.kalkulacija_id = k.id) as broj_prijemnica,
       (select listagg(kf.naziv, ', ') within group (order by kf.id)
          from kalkulacija_kuf kk join kuf kf on kf.id = kk.kuf_id
         where kk.kalkulacija_id = k.id)                                 as fakture,
       (select nvl(sum(kk.iznos), 0) from kalkulacija_kuf kk where kk.kalkulacija_id = k.id)            as iznos_faktura,
       (select nvl(sum(t.iznos), 0) from kalkulacija_troskovi t where t.kalkulacija_id = k.id)          as iznos_troskova,
       (select nvl(sum(ks.nabavna_vrijednost), 0) from kalkulacija_stavke ks where ks.kalkulacija_id = k.id) as nabavna_vrijednost,
       k.created_by
  from kalkulacije k
  left join skladista s on s.id = k.skladiste_id
  left join sif.acc_tipovi_skladista ts on ts.id = s.tip_skladista_id;

-- zaključene ulazne fakture firme sa raspoloživim iznosom (za izbor u kalkulaciji)
create or replace force view vw_rm_kalk_fakture as
select k.id,
       k.ooj_id,
       k.naziv,
       k.naziv_fakture,
       k.datum_fakture,
       k.klijent_id,
       kl.naziv                                                          as klijent_naziv,
       k.iznos_bez_pdv,
       k.iznos_sa_pdv,
       rm_kalkulacija_pkg.kuf_raspolozivo(k.id, 'N')                     as raspolozivo_bez_pdv,
       rm_kalkulacija_pkg.kuf_raspolozivo(k.id, 'Y')                     as raspolozivo_sa_pdv
  from kuf k
  join sif.vrste_dokumenata vd on vd.id = k.vrsta_dokumenta_id
  left join sec_klijenti kl on kl.id = k.klijent_id
 where upper(vd.sifra) = 'UF'
   and nvl(k.status, 'P') = 'Z'
   and nvl(k.stornirano, 'N') = 'N'
   and k.storniran_id is null;

create or replace force view vw_rm_kalkulacija_stavke as
select ks.id,
       ks.kalkulacija_id,
       ks.operacija_id,
       o.naziv                                                           as prijemnica,
       ks.operacija_stavka_id,
       ks.stavka_id,
       st.sifra,
       st.naziv,
       jm.naziv                                                          as jm_naziv,
       ks.redni_broj,
       ks.kolicina,
       ks.ulazna_cijena,
       ks.osnovica,
       ks.rucni_iznos,
