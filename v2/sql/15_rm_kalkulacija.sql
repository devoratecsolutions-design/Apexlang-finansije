    procedure snimi_prijemnicu_red (p_red_id in out number, p_id in number, p_operacija_id in number) is
        l_stara number;
    begin
        if p_red_id is null then
            dodaj_prijemnicu(p_id, p_operacija_id);
            select max(id) into p_red_id from kalkulacija_operacije where kalkulacija_id = p_id and operacija_id = p_operacija_id;
        else
            select operacija_id into l_stara from kalkulacija_operacije where id = p_red_id and kalkulacija_id = p_id;
            if l_stara <> p_operacija_id then
                ukloni_prijemnicu(p_id, l_stara);
                dodaj_prijemnicu(p_id, p_operacija_id);
                select max(id) into p_red_id from kalkulacija_operacije where kalkulacija_id = p_id and operacija_id = p_operacija_id;
            end if;
        end if;
    end snimi_prijemnicu_red;

    procedure obrisi_prijemnicu_red (p_red_id in number) is
