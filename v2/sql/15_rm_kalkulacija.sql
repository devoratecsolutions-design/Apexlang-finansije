create or replace package body rm_kalkulacija_pkg as

    type t_artikal is record (stavka_id number, sifra varchar2(255), naziv varchar2(255), jm varchar2(255),
                              kol number, osn number, iznos number, sacuvano number);
    type t_artikli is table of t_artikal index by pls_integer;


    procedure greska (p_tekst in varchar2) is
    begin
        raise_application_error(-20201, 'Greška CORP-RM: ' || p_tekst);
    end greska;

    function robno (p_id in number) return boolean is
        l_n number;
    begin
        select count(*) into l_n
          from kalkulacije k
          join skladista s on s.id = k.skladiste_id
          join sif.acc_tipovi_skladista ts on ts.id = s.tip_skladista_id
         where k.id = p_id and upper(ts.sifra) = 'ROB';
        return l_n > 0;
    end robno;

    --------------------------------------------------------------------- status
    function razlog_zabrane (p_id in number) return varchar2 is
    begin
        for k in (select k.status, k.zakljucano, k.datum, k.ooj_id from kalkulacije k where k.id = p_id) loop
            if nvl(k.status, case when k.zakljucano = 'Y' then 'Z' else 'P' end) = 'Z' then
                return 'Kalkulacija je zaključena.';
            end if;
            for p in (select period_zakljucan_do from core.ooj where id = k.ooj_id) loop
                if p.period_zakljucan_do is not null and trunc(k.datum) < trunc(p.period_zakljucan_do) then
                    return 'Kalkulacija je u zaključanom periodu.';
                end if;
            end loop;
            return null;
        end loop;
        return 'Kalkulacija ne postoji.';
    end razlog_zabrane;

    function izmjenjiva (p_id in number) return varchar2 is
    begin
        return case when p_id is null or razlog_zabrane(p_id) is null then 'Y' else 'N' end;
    end izmjenjiva;

    procedure provjeri_izmjenu (p_id in number) is
        l_r varchar2(4000) := razlog_zabrane(p_id);
    begin
        if l_r is not null then
            greska(l_r || ' Izmjene nisu moguće.');
        end if;
    end provjeri_izmjenu;

    --------------------------------------------------------------------- zaglavlje
    function snimi (
        p_id               in number,
        p_ooj_id           in number,
        p_godina           in number,
        p_skladiste_id     in number,
        p_datum            in date,
        p_nacin_raspodjele in varchar2,
        p_opis             in varchar2
    ) return number is
        l_id    number := p_id;
        l_broj  number;
        l_naziv varchar2(255);
        l_n     number;
        l_zak   date;
        l_max   date;
        l_stari number;
    begin
        if l_id is not null then
            provjeri_izmjenu(l_id);
        end if;
        if p_skladiste_id is null then
            greska('Izaberite skladište.');
        end if;
        select count(*) into l_n from skladista where id = p_skladiste_id and ooj_id = p_ooj_id;
        if l_n = 0 then
            greska('Skladište ne pripada firmi.');
        end if;
        if p_datum is null then
            greska('Datum kalkulacije je obavezan.');
        end if;
        if extract(year from p_datum) <> p_godina then
            greska('Datum kalkulacije mora biti u ' || p_godina || '. godini.');
        end if;
        if trunc(p_datum) > trunc(sysdate) then
            greska('Datum kalkulacije ne može biti u budućnosti.');
        end if;
        select max(period_zakljucan_do) into l_zak from core.ooj where id = p_ooj_id;
        if l_zak is not null and trunc(p_datum) < trunc(l_zak) then
            greska('Datum kalkulacije je u zaključanom periodu.');
        end if;
        if nvl(p_nacin_raspodjele, 'V') not in ('V', 'K', 'L', 'R') then
            greska('Nepoznat način raspodjele.');
        end if;

        if l_id is null then
            if not core.protokoli_pkg.check_brojac(p_ooj_id, 'kalk', p_godina) then
                greska('Nije definisan brojač za kalkulacije (KALK) u ' || p_godina || '. godini. Podesite numeraciju dokumenata.');
            end if;
            core.protokoli_pkg.get_brojac(p_ooj_id => p_ooj_id, p_godina => p_godina, p_vrsta_naloga_sifra => 'kalk',
                                          p_broj => l_broj, p_naziv => l_naziv);
            insert into kalkulacije (ooj_id, godina, broj, naziv, datum, opis, skladiste_id, status, zakljucano,
                                     nacin_raspodjele, valid)
            values (p_ooj_id, p_godina, l_broj, l_naziv, trunc(p_datum), p_opis, p_skladiste_id, 'P', 'N',
                    nvl(p_nacin_raspodjele, 'V'), 'Y')
            returning id into l_id;
            core.protokoli_pkg.update_brojac(p_ooj_id => p_ooj_id, p_vrsta_naloga_sifra => 'kalk', p_godina => p_godina,
                                             p_value => 1);
        else
            select max(o.datum) into l_max
              from kalkulacija_operacije ko join operacije o on o.id = ko.operacija_id
             where ko.kalkulacija_id = l_id;
            if l_max is not null and trunc(p_datum) < trunc(l_max) then
                greska('Datum kalkulacije ne može biti prije datuma prijemnice (' || to_char(l_max, 'DD.MM.YYYY') || ').');
            end if;
            select count(*) into l_n from kalkulacija_operacije where kalkulacija_id = l_id;
            select nvl(skladiste_id, -1) into l_stari from kalkulacije where id = l_id;
            if l_n > 0 and l_stari <> p_skladiste_id then
                greska('Skladište se ne može promijeniti dok kalkulacija ima prijemnice.');
            end if;
            update kalkulacije
               set datum = trunc(p_datum), opis = p_opis, skladiste_id = p_skladiste_id,
                   nacin_raspodjele = nvl(p_nacin_raspodjele, 'V')
             where id = l_id;
        end if;
        return l_id;
    end snimi;

    procedure obrisi (p_id in number) is
    begin
        provjeri_izmjenu(p_id);
        update operacije set kalkulacija_id = null where kalkulacija_id = p_id;
        delete from kalkulacija_raspodjela where kalkulacija_id = p_id;
        delete from kalkulacija_stavke where kalkulacija_id = p_id;
        delete from kalkulacija_troskovi where kalkulacija_id = p_id;
        delete from kalkulacija_kuf where kalkulacija_id = p_id;
        delete from kalkulacija_operacije where kalkulacija_id = p_id;
        delete from kalkulacije where id = p_id;
    end obrisi;

    --------------------------------------------------------------------- prijemnice
    procedure dodaj_prijemnicu (p_id in number, p_operacija_id in number) is
        l_skl   number;
        l_datum date;
        l_ok    number;
        l_cj    number;
    begin
        provjeri_izmjenu(p_id);
        if p_operacija_id is null then
            greska('Izaberite prijemnicu.');
        end if;
        select skladiste_id, datum into l_skl, l_datum from kalkulacije where id = p_id;
        select count(*) into l_ok
          from operacije o
          join sif.vrste_dokumenata vd on vd.id = o.vrsta_dokumenta_id
         where o.id = p_operacija_id
           and upper(vd.sifra) = 'PRI'
           and o.skladiste_id = l_skl
           and nvl(o.status, 'P') = 'P'
           and nvl(o.stornirano, 'N') = 'N';
        if l_ok = 0 then
            greska('Prijemnica mora biti u pripremi i sa skladišta kalkulacije.');
        end if;
        select count(*) into l_ok from kalkulacija_operacije where operacija_id = p_operacija_id;
        if l_ok > 0 then
            greska('Prijemnica je već uključena u kalkulaciju.');
        end if;
        select count(*) into l_ok from operacije where id = p_operacija_id and datum > l_datum;
        if l_ok > 0 then
            greska('Datum prijemnice je poslije datuma kalkulacije - promijenite datum kalkulacije.');
        end if;

        insert into kalkulacija_operacije (kalkulacija_id, operacija_id) values (p_id, p_operacija_id);
        update operacije set kalkulacija_id = p_id where id = p_operacija_id;

        select max(s.cjenovnik_id) into l_cj from skladista s where s.id = l_skl;
        insert into kalkulacija_stavke (kalkulacija_id, operacija_stavka_id, operacija_id, stavka_id, redni_broj,
                                        kolicina, ulazna_cijena, osnovica, pdv_stopa, vpc, mpc)
        select p_id, os.id, os.operacija_id, os.stavka_id, os.redni_broj,
               os.kolicina, os.nabavna_cijena, round(os.kolicina * nvl(os.nabavna_cijena, 0), 2),
               nvl(pi.vrijednost, 17),
               cs.vpc, cs.mpc
          from operacija_stavke os
          join sec_stavke st on st.id = os.stavka_id
          left join sif.acc_pdv_indikatori pi on pi.id = st.pdv_indikator_id
          outer apply (select c.vpc, c.mpc
                         from cjenovnik_stavke c
                        where c.cjenovnik_id = l_cj and c.stavka_id = os.stavka_id and c.valid = 'Y'
                        order by c.datum desc, c.id desc
                        fetch first 1 row only) cs
         where os.operacija_id = p_operacija_id;
        ponisti_raspodjelu(p_id);
        preracunaj(p_id);
    end dodaj_prijemnicu;

    procedure ukloni_prijemnicu (p_id in number, p_operacija_id in number) is
    begin
        provjeri_izmjenu(p_id);
        ponisti_raspodjelu(p_id);
        delete from kalkulacija_stavke where kalkulacija_id = p_id and operacija_id = p_operacija_id;
        delete from kalkulacija_operacije where kalkulacija_id = p_id and operacija_id = p_operacija_id;
        update operacije set kalkulacija_id = null where id = p_operacija_id and kalkulacija_id = p_id;
        preracunaj(p_id);
    end ukloni_prijemnicu;

    --------------------------------------------------------------------- fakture i troškovi
    -- iskorišteni dio fakture je udio (iznos / osnova reda), pa se miješanje "sa" i "bez PDV-a" računa ispravno
    function kuf_raspolozivo (p_kuf_id in number, p_sa_pdv in varchar2, p_bez_reda in number default null) return number is
        l_sa  number;
        l_bez number;
        l_udio number;
    begin
        select nvl(iznos_sa_pdv, 0), nvl(iznos_bez_pdv, 0) into l_sa, l_bez from kuf where id = p_kuf_id;
        select nvl(sum(case when kk.sa_pdv = 'Y' then case when l_sa = 0 then 0 else kk.iznos / l_sa end
                            else case when l_bez = 0 then 0 else kk.iznos / l_bez end end), 0)
          into l_udio
          from kalkulacija_kuf kk
         where kk.kuf_id = p_kuf_id
           and kk.iznos is not null
           and kk.id <> nvl(p_bez_reda, -1);
        return greatest(round((1 - l_udio) * case when p_sa_pdv = 'Y' then l_sa else l_bez end, 2), 0);
    exception
        when no_data_found then
            return 0;
    end kuf_raspolozivo;

    function kuf_info (p_kuf_id in number, p_sa_pdv in varchar2, p_red_id in number) return varchar2 is
        l_json varchar2(1000);
    begin
        select json_object('osnova' value case when p_sa_pdv = 'Y' then iznos_sa_pdv else iznos_bez_pdv end,
                           'rasp' value kuf_raspolozivo(p_kuf_id, p_sa_pdv, p_red_id))
          into l_json
          from kuf where id = p_kuf_id;
        return l_json;
    exception
        when no_data_found then
            return '{}';
    end kuf_info;

    procedure snimi_kuf (p_red_id in out number, p_id in number, p_kuf_id in number, p_sa_pdv in varchar2,
                         p_iznos in number, p_pdv_sistem in varchar2, p_nacin in varchar2 default 'V') is
        l_nacin  varchar2(1) := nvl(p_nacin, 'V');
        l_ok     number;
        l_sa_pdv varchar2(1) := case when nvl(p_pdv_sistem, 'N') = 'Y' then nvl(p_sa_pdv, 'N') else 'Y' end;
        l_rasp   number;
    begin
        provjeri_izmjenu(p_id);
        if p_kuf_id is null then
            greska('Izaberite ulaznu fakturu.');
        end if;
        select count(*) into l_ok
          from kuf k
          join kalkulacije kl on kl.id = p_id and kl.ooj_id = k.ooj_id
          join sif.vrste_dokumenata vd on vd.id = k.vrsta_dokumenta_id
         where k.id = p_kuf_id
           and upper(vd.sifra) = 'UF'
           and nvl(k.status, 'P') = 'Z'
           and nvl(k.stornirano, 'N') = 'N'
           and k.storniran_id is null;
        if l_ok = 0 then
            greska('U kalkulaciju se uključuju samo zaključene ulazne fakture firme.');
        end if;
        if p_iznos is null or p_iznos <= 0 then
            greska('Iznos za raspodjelu mora biti veći od nule.');
        end if;
        l_rasp := kuf_raspolozivo(p_kuf_id, l_sa_pdv, p_red_id);
        if p_iznos > l_rasp then
            greska('Iznos za raspodjelu je veći od raspoloživog iznosa fakture (' || to_char(l_rasp, 'FM999G999G999G990D00') || ').');
        end if;
        select count(*) into l_ok from kalkulacija_kuf where kalkulacija_id = p_id and kuf_id = p_kuf_id and id <> nvl(p_red_id, -1);
        if l_ok > 0 then
            greska('Faktura je već dodata u ovu kalkulaciju - promijenite iznos na postojećem redu.');
        end if;
        if l_nacin not in ('V', 'K', 'L', 'R') then
            greska('Nepoznat način raspodjele.');
        end if;
        if p_red_id is null then
            insert into kalkulacija_kuf (kalkulacija_id, kuf_id, iznos, sa_pdv, tip_kalkulacije, nacin_raspodjele)
            values (p_id, p_kuf_id, round(p_iznos, 2), l_sa_pdv, 'U', l_nacin)
            returning id into p_red_id;
            ponisti_raspodjelu(p_id);                    -- nova faktura: dotadašnja raspodjela se poništava
        else
            select count(*) into l_ok from kalkulacija_kuf
             where id = p_red_id and kuf_id = p_kuf_id and iznos = round(p_iznos, 2) and sa_pdv = l_sa_pdv
               and nvl(nacin_raspodjele, 'V') = l_nacin;
            if l_ok = 0 then
                update kalkulacija_kuf
                   set kuf_id = p_kuf_id, iznos = round(p_iznos, 2), sa_pdv = l_sa_pdv, nacin_raspodjele = l_nacin
                 where id = p_red_id and kalkulacija_id = p_id;
                ponisti_raspodjelu(p_id, p_kuf_red_id => p_red_id);
            end if;
        end if;
    end snimi_kuf;

    procedure obrisi_kuf (p_red_id in number) is
        l_id number;
    begin
        select kalkulacija_id into l_id from kalkulacija_kuf where id = p_red_id;
        provjeri_izmjenu(l_id);
        delete from kalkulacija_raspodjela where kalkulacija_kuf_id = p_red_id;
        delete from kalkulacija_kuf where id = p_red_id;
    exception
        when no_data_found then
            null;
    end obrisi_kuf;

    procedure snimi_trosak (p_red_id in out number, p_id in number, p_opis in varchar2, p_iznos in number,
                            p_nacin in varchar2 default 'V') is
        l_nacin varchar2(1) := nvl(p_nacin, 'V');
        l_ok    number;
    begin
        provjeri_izmjenu(p_id);
        if trim(p_opis) is null then
            greska('Unesite opis zavisnog troška.');
        end if;
        if p_iznos is null or p_iznos <= 0 then
            greska('Iznos zavisnog troška mora biti veći od nule.');
        end if;
        if l_nacin not in ('V', 'K', 'L', 'R') then
            greska('Nepoznat način raspodjele.');
        end if;
        if p_red_id is null then
            insert into kalkulacija_troskovi (kalkulacija_id, opis, iznos, nacin_raspodjele)
            values (p_id, trim(p_opis), round(p_iznos, 2), l_nacin)
            returning id into p_red_id;
            ponisti_raspodjelu(p_id);                    -- novi trošak: dotadašnja raspodjela se poništava
        else
            select count(*) into l_ok from kalkulacija_troskovi
             where id = p_red_id and iznos = round(p_iznos, 2) and nvl(nacin_raspodjele, 'V') = l_nacin;
            update kalkulacija_troskovi set opis = trim(p_opis), iznos = round(p_iznos, 2), nacin_raspodjele = l_nacin
             where id = p_red_id and kalkulacija_id = p_id;
            if l_ok = 0 then
                ponisti_raspodjelu(p_id, p_trosak_id => p_red_id);
            end if;
        end if;
    end snimi_trosak;

    procedure obrisi_trosak (p_red_id in number) is
        l_id number;
    begin
        select kalkulacija_id into l_id from kalkulacija_troskovi where id = p_red_id;
        provjeri_izmjenu(l_id);
        delete from kalkulacija_raspodjela where kalkulacija_trosak_id = p_red_id;
        delete from kalkulacija_troskovi where id = p_red_id;
    exception
        when no_data_found then
            null;
    end obrisi_trosak;

    --------------------------------------------------------------------- stavke i raspodjela
    procedure ponisti_raspodjelu (p_id in number, p_kuf_red_id in number default null, p_trosak_id in number default null) is
    begin
        if p_kuf_red_id is null and p_trosak_id is null then
            delete from kalkulacija_raspodjela where kalkulacija_id = p_id;
        else
            delete from kalkulacija_raspodjela
             where kalkulacija_id = p_id
               and ((p_kuf_red_id is not null and kalkulacija_kuf_id = p_kuf_red_id)
                    or (p_trosak_id is not null and kalkulacija_trosak_id = p_trosak_id));
        end if;
        update kalkulacija_stavke set nabavna_vrijednost = null, nabavna_cijena = null, cijena = null, iznos = null,
                                      marza_iznos = null
         where kalkulacija_id = p_id;
    end ponisti_raspodjelu;

    -- automatska raspodjela jednog izvora: V = po vrijednosti, K = po količini, L = linearno
    procedure rasporedi_izvor (p_id in number, p_kuf_red_id in number, p_trosak_id in number, p_iznos in number, p_nacin in varchar2) is
        l_nacin varchar2(1) := p_nacin;
        l_kljuc number;
        l_suma  number;
        l_max   number;
    begin
        delete from kalkulacija_raspodjela
         where kalkulacija_id = p_id
           and ((p_kuf_red_id is not null and kalkulacija_kuf_id = p_kuf_red_id)
                or (p_trosak_id is not null and kalkulacija_trosak_id = p_trosak_id));
        if l_nacin = 'R' then
            -- ručno: red po stavci, iznos upisuje korisnik
            insert into kalkulacija_raspodjela (kalkulacija_id, kalkulacija_kuf_id, kalkulacija_trosak_id, kalkulacija_stavka_id, iznos)
            select p_id, p_kuf_red_id, p_trosak_id, ks.id, null from kalkulacija_stavke ks where ks.kalkulacija_id = p_id;
            return;
        end if;
        select case l_nacin when 'V' then sum(nvl(osnovica, 0)) when 'K' then sum(nvl(kolicina, 0)) else count(*) end
          into l_kljuc from kalkulacija_stavke where kalkulacija_id = p_id;
        if l_nacin = 'V' and nvl(l_kljuc, 0) = 0 then
            l_nacin := 'K';                              -- prijemnica bez cijena: po količini
            select sum(nvl(kolicina, 0)) into l_kljuc from kalkulacija_stavke where kalkulacija_id = p_id;
        end if;
        if nvl(l_kljuc, 0) = 0 then
            return;
        end if;
        insert into kalkulacija_raspodjela (kalkulacija_id, kalkulacija_kuf_id, kalkulacija_trosak_id, kalkulacija_stavka_id, iznos)
        select p_id, p_kuf_red_id, p_trosak_id, ks.id,
               round(p_iznos * case l_nacin when 'V' then nvl(ks.osnovica, 0) when 'K' then nvl(ks.kolicina, 0) else 1 end / l_kljuc, 2)
          from kalkulacija_stavke ks
         where ks.kalkulacija_id = p_id;
        -- razlika zaokruživanja na stavku najveće vrijednosti
        select nvl(sum(r.iznos), 0) into l_suma
          from kalkulacija_raspodjela r
         where r.kalkulacija_id = p_id
           and ((p_kuf_red_id is not null and r.kalkulacija_kuf_id = p_kuf_red_id)
                or (p_trosak_id is not null and r.kalkulacija_trosak_id = p_trosak_id));
        if l_suma <> p_iznos then
            select max(id) keep (dense_rank first order by nvl(osnovica, 0) desc, nvl(kolicina, 0) desc, id)
              into l_max from kalkulacija_stavke where kalkulacija_id = p_id;
            update kalkulacija_raspodjela r
               set r.iznos = r.iznos + (p_iznos - l_suma)
             where r.kalkulacija_stavka_id = l_max
               and ((p_kuf_red_id is not null and r.kalkulacija_kuf_id = p_kuf_red_id)
                    or (p_trosak_id is not null and r.kalkulacija_trosak_id = p_trosak_id));
        end if;
    end rasporedi_izvor;

    procedure rasporedi (p_id in number) is
        l_n number;
    begin
        provjeri_izmjenu(p_id);
        select count(*) into l_n from kalkulacija_stavke where kalkulacija_id = p_id;
        if l_n = 0 then
            greska('Dodajte prijemnice prije raspodjele.');
        end if;
        -- automatski izvori se raspoređuju ponovo; ručni samo ako još nemaju redove (upisani iznosi ostaju)
        for f in (select id, iznos, nvl(nacin_raspodjele, 'V') as nacin from kalkulacija_kuf where kalkulacija_id = p_id) loop
            select count(*) into l_n from kalkulacija_raspodjela where kalkulacija_kuf_id = f.id;
            if f.nacin <> 'R' or l_n = 0 then
                rasporedi_izvor(p_id, f.id, null, f.iznos, f.nacin);
            end if;
        end loop;
        for tr in (select id, iznos, nvl(nacin_raspodjele, 'V') as nacin from kalkulacija_troskovi where kalkulacija_id = p_id) loop
            select count(*) into l_n from kalkulacija_raspodjela where kalkulacija_trosak_id = tr.id;
            if tr.nacin <> 'R' or l_n = 0 then
                rasporedi_izvor(p_id, null, tr.id, tr.iznos, tr.nacin);
            end if;
        end loop;
        preracunaj(p_id);
    end rasporedi;

    procedure snimi_raspodjelu (p_red_id in number, p_iznos in number) is
        l_id    number;
        l_nacin varchar2(1);
    begin
        select r.kalkulacija_id, coalesce(kk.nacin_raspodjele, kt.nacin_raspodjele, 'V')
          into l_id, l_nacin
          from kalkulacija_raspodjela r
          left join kalkulacija_kuf kk on kk.id = r.kalkulacija_kuf_id
          left join kalkulacija_troskovi kt on kt.id = r.kalkulacija_trosak_id
         where r.id = p_red_id;
        provjeri_izmjenu(l_id);
        if l_nacin <> 'R' then
            greska('Iznos se upisuje samo kod ručne raspodjele. Promijenite način raspodjele izvora u "Ručno".');
        end if;
        if nvl(p_iznos, 0) < 0 then
            greska('Iznos raspodjele ne može biti negativan.');
        end if;
        update kalkulacija_raspodjela set iznos = round(p_iznos, 2) where id = p_red_id;
    end snimi_raspodjelu;

    function izvor_rasporedjen (p_kuf_red_id in number, p_trosak_id in number) return varchar2 is
        l_iznos number;
        l_suma  number;
        l_n     number;
    begin
        if p_kuf_red_id is not null then
            select max(iznos) into l_iznos from kalkulacija_kuf where id = p_kuf_red_id;
            select count(*), nvl(sum(iznos), 0) into l_n, l_suma from kalkulacija_raspodjela where kalkulacija_kuf_id = p_kuf_red_id;
        else
            select max(iznos) into l_iznos from kalkulacija_troskovi where id = p_trosak_id;
            select count(*), nvl(sum(iznos), 0) into l_n, l_suma from kalkulacija_raspodjela where kalkulacija_trosak_id = p_trosak_id;
        end if;
        return case when l_n > 0 and abs(l_suma - nvl(l_iznos, 0)) < 0.005 then 'Y' else 'N' end;
    end izvor_rasporedjen;

    function sve_rasporedjeno (p_id in number) return varchar2 is
        l_n number;
    begin
        select count(*) into l_n from kalkulacija_stavke where kalkulacija_id = p_id;
        if l_n = 0 then
            return 'N';
        end if;
        select count(*) into l_n from (
            select id from kalkulacija_kuf where kalkulacija_id = p_id and izvor_rasporedjen(id, null) = 'N'
            union all
            select id from kalkulacija_troskovi where kalkulacija_id = p_id and izvor_rasporedjen(null, id) = 'N');
        if l_n > 0 then
            return 'N';
        end if;
        select count(*) into l_n from (
            select id from kalkulacija_kuf where kalkulacija_id = p_id
            union all
            select id from kalkulacija_troskovi where kalkulacija_id = p_id);
        return case when l_n > 0 then 'Y' else 'N' end;
    end sve_rasporedjeno;

    procedure snimi_stavku (p_red_id in number, p_marza_procenat in number, p_vpc in number, p_mpc in number) is
        l_id number;
    begin
        select kalkulacija_id into l_id from kalkulacija_stavke where id = p_red_id;
        provjeri_izmjenu(l_id);
        if sve_rasporedjeno(l_id) = 'N' then
            greska('Veleprodajne i maloprodajne cijene se formiraju tek kad su sve fakture i troškovi raspoređeni.');
        end if;
        if nvl(p_vpc, 0) < 0 or nvl(p_mpc, 0) < 0 then
            greska('Cijene ne mogu biti negativne.');
        end if;
        update kalkulacija_stavke
           set marza_procenat = p_marza_procenat,
               vpc            = round(p_vpc, 4),
               mpc            = round(p_mpc, 2)
         where id = p_red_id;
    end snimi_stavku;

    function ukupno_za_raspodjelu (p_id in number) return number is
        l_kuf number;
        l_tr  number;
    begin
        select nvl(sum(iznos), 0) into l_kuf from kalkulacija_kuf where kalkulacija_id = p_id;
        select nvl(sum(iznos), 0) into l_tr from kalkulacija_troskovi where kalkulacija_id = p_id;
        return l_kuf + l_tr;
    end ukupno_za_raspodjelu;

    -- nabavna vrijednost stavke = zbir raspodjela svih izvora; nabavna cijena = vrijednost / količina
    procedure preracunaj (p_id in number) is
    begin
        update kalkulacija_stavke ks
           set ks.nabavna_vrijednost = (select sum(r.iznos) from kalkulacija_raspodjela r where r.kalkulacija_stavka_id = ks.id)
         where ks.kalkulacija_id = p_id;
        update kalkulacija_stavke ks
           set ks.nabavna_cijena = case when ks.nabavna_vrijednost is null or nvl(ks.kolicina, 0) = 0 then null
                                        else round(ks.nabavna_vrijednost / ks.kolicina, 6) end,
               ks.cijena         = case when ks.nabavna_vrijednost is null or nvl(ks.kolicina, 0) = 0 then null
                                        else round(ks.nabavna_vrijednost / ks.kolicina, 6) end,
               ks.iznos          = ks.nabavna_vrijednost
         where ks.kalkulacija_id = p_id;

        if robno(p_id) and sve_rasporedjeno(p_id) = 'Y' then
            -- VPC iz marže kad nije unesena; MPC iz VPC kad nije unesena; marža iz VPC i nabavne cijene
            update kalkulacija_stavke ks
               set ks.vpc = nvl(ks.vpc, case when ks.marza_procenat is not null
                                             then round(ks.nabavna_cijena * (1 + ks.marza_procenat / 100), 2) end)
             where ks.kalkulacija_id = p_id;
            update kalkulacija_stavke ks
               set ks.mpc = nvl(ks.mpc, case when ks.vpc is not null then round(ks.vpc * (1 + nvl(ks.pdv_stopa, 0) / 100), 2) end),
                   ks.marza_iznos = case when ks.vpc is not null then round(ks.vpc - ks.nabavna_cijena, 4) end,
                   ks.marza_procenat = case when ks.vpc is not null and ks.nabavna_cijena > 0
                                            then round((ks.vpc - ks.nabavna_cijena) / ks.nabavna_cijena * 100, 2)
                                            else ks.marza_procenat end
             where ks.kalkulacija_id = p_id;
        end if;
    end preracunaj;

    --------------------------------------------------------------------- zaključavanje
    function provjeri_zakljucavanje (p_id in number) return varchar2 is
        l_n      number;
        l_ukupno number := ukupno_za_raspodjelu(p_id);
        l_rasp   number;
        l_poruka varchar2(4000);
    begin
        if razlog_zabrane(p_id) is not null then
            return razlog_zabrane(p_id);
        end if;
        select count(*) into l_n from kalkulacija_operacije where kalkulacija_id = p_id;
        if l_n = 0 then
            return 'Dodajte bar jednu prijemnicu.';
        end if;
        if l_ukupno <= 0 then
            return 'Dodajte ulazne fakture ili zavisne troškove čiji se iznos raspoređuje.';
        end if;
        for o in (select ko.operacija_id, op.naziv from kalkulacija_operacije ko join operacije op on op.id = ko.operacija_id
                   where ko.kalkulacija_id = p_id) loop
            l_poruka := rm_dokument_pkg.provjeri_kompletnost(o.operacija_id);
            if l_poruka is not null then
                return 'Prijemnica ' || o.naziv || ': ' || l_poruka;
            end if;
        end loop;
        for f in (select kk.id, kk.kuf_id, kk.sa_pdv, kk.iznos, k.naziv from kalkulacija_kuf kk join kuf k on k.id = kk.kuf_id
                   where kk.kalkulacija_id = p_id) loop
            if f.iznos > kuf_raspolozivo(f.kuf_id, f.sa_pdv, f.id) then
                return 'Iznos fakture ' || f.naziv || ' je veći od raspoloživog.';
            end if;
        end loop;
        for f in (select kk.id, k.naziv from kalkulacija_kuf kk join kuf k on k.id = kk.kuf_id where kk.kalkulacija_id = p_id) loop
            if izvor_rasporedjen(f.id, null) = 'N' then
                return 'Faktura ' || f.naziv || ' nije (potpuno) raspoređena na stavke.';
            end if;
        end loop;
        for tr in (select id, opis from kalkulacija_troskovi where kalkulacija_id = p_id) loop
            if izvor_rasporedjen(null, tr.id) = 'N' then
                return 'Zavisni trošak "' || tr.opis || '" nije (potpuno) raspoređen na stavke.';
            end if;
        end loop;
        select nvl(sum(nabavna_vrijednost), 0) into l_rasp from kalkulacija_stavke where kalkulacija_id = p_id;
        if abs(l_rasp - l_ukupno) > 0.005 then
            return 'Raspoređeno je ' || to_char(l_rasp, 'FM999G999G999G990D00') || ', a za raspodjelu je '
                   || to_char(l_ukupno, 'FM999G999G999G990D00') || ' KM.';
        end if;
        if robno(p_id) then
            select count(*) into l_n from kalkulacija_stavke
             where kalkulacija_id = p_id and (nvl(vpc, 0) <= 0 or nvl(mpc, 0) <= 0);
            if l_n > 0 then
                return 'Robno skladište: unesite veleprodajnu i maloprodajnu cijenu za sve stavke.';
            end if;
        end if;
        return null;
    end provjeri_zakljucavanje;

    procedure zakljucaj (p_id in number) is
        l_poruka varchar2(4000);
        l_robno  boolean;
    begin
        preracunaj(p_id);
        l_poruka := provjeri_zakljucavanje(p_id);
        if l_poruka is not null then
            greska(l_poruka);
        end if;
        l_robno := robno(p_id);
        -- cijene u prijemnice; ulazna cijena prijemnice ostaje sačuvana u kalkulaciji (za otključavanje)
        for s in (select * from kalkulacija_stavke where kalkulacija_id = p_id) loop
            update operacija_stavke
               set nabavna_cijena     = s.nabavna_cijena,
                   obradjena_kolicina = kolicina,
                   marza              = case when l_robno then s.marza_iznos end,
                   marza_procenat     = case when l_robno then s.marza_procenat end,
                   porez_procenat     = case when l_robno then s.pdv_stopa end,
                   mpc                = case when l_robno then s.mpc end
             where id = s.operacija_stavka_id;
        end loop;
        update operacije o
           set o.status = 'Z', o.zakljucano = 'Y', o.kalkulacija_id = p_id
         where o.id in (select operacija_id from kalkulacija_operacije where kalkulacija_id = p_id);
        update kalkulacije set status = 'Z', zakljucano = 'Y' where id = p_id;
    end zakljucaj;

    function razlog_zabrane_otkljucavanja (p_id in number, p_admin in varchar2) return varchar2 is
        l_n     number;
        l_datum date;
    begin
        for k in (select k.status, k.skladiste_id from kalkulacije k where k.id = p_id) loop
            if nvl(k.status, 'P') <> 'Z' then
                return 'Kalkulacija nije zaključena.';
            end if;
            if nvl(p_admin, 'N') <> 'Y' then
                return 'Kalkulaciju može otključati samo administrator.';
            end if;
            if robno(p_id) then
                return 'Kalkulacija robnog skladišta se ne može otključati.';
            end if;
            select min(o.datum) into l_datum
              from kalkulacija_operacije ko join operacije o on o.id = ko.operacija_id
             where ko.kalkulacija_id = p_id;
            select count(*) into l_n
              from operacija_stavke os
              join operacije o on o.id = os.operacija_id
              left join sif.vrste_dokumenata vd on vd.id = o.vrsta_dokumenta_id
              left join sif.acc_tipovi_kretanja_robe t on t.id = o.tip_kretanja_id
             where o.skladiste_id = k.skladiste_id
               and nvl(o.stornirano, 'N') = 'N'
               and o.datum >= l_datum
               and coalesce(rm_dokument_pkg.tip_kretanja(vd.sifra), t.tip_kretanja) = 'I'
               and os.stavka_id in (select ks.stavka_id from kalkulacija_stavke ks where ks.kalkulacija_id = p_id);
            if l_n > 0 then
                return 'Roba iz kalkulacije je već izdavana sa skladišta - kalkulacija se ne može otključati.';
            end if;
            return null;
        end loop;
        return 'Kalkulacija ne postoji.';
    end razlog_zabrane_otkljucavanja;

    procedure otkljucaj (p_id in number, p_admin in varchar2) is
        l_r varchar2(4000) := razlog_zabrane_otkljucavanja(p_id, p_admin);
    begin
        if l_r is not null then
            greska(l_r);
        end if;
        for s in (select * from kalkulacija_stavke where kalkulacija_id = p_id) loop
            update operacija_stavke
               set nabavna_cijena = s.ulazna_cijena, obradjena_kolicina = null,
                   marza = null, marza_procenat = null, porez_procenat = null, mpc = null
             where id = s.operacija_stavka_id;
        end loop;
        update operacije o
           set o.status = 'P', o.zakljucano = 'N'
         where o.id in (select operacija_id from kalkulacija_operacije where kalkulacija_id = p_id);
        update kalkulacije set status = 'P', zakljucano = 'N' where id = p_id;
    end otkljucaj;

