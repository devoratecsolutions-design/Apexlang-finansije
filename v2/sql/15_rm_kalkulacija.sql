/*
================================================================================
  ESSCOM Finansije - 15_rm_kalkulacija.sql
  Pokrenuti kao: ACCOUNTING, POSLIJE 14_rm_skladista.sql

  Kalkulacija (korak R6). Nabavnu vrijednost stavki prijemnica čine raspoređeni
  iznosi ulaznih faktura (UF) i ručno unesenih zavisnih troškova.
    - kalkulacija pripada skladištu i obuhvata jednu ili više prijemnica (u pripremi)
    - fakture: samo zaključene UF sa raspoloživim iznosom; firma van PDV sistema
      raspoređuje iznos sa PDV-om, firma u PDV sistemu bira sa ili bez PDV-a;
      jedna faktura se može raspoređivati na više kalkulacija (dio iznosa)
    - svaka faktura i svaki zavisni trošak se posebno raspoređuje na stavke prijemnica
      (KALKULACIJA_RASPODJELA), svaki svojim načinom: po vrijednosti (V, podrazumijevano),
      po količini (K), linearno (L) ili ručno (R); razlika zaokruživanja na stavku
      najveće vrijednosti; nabavna vrijednost / cijena stavke = zbir raspodjela
    - dodavanje ili uklanjanje prijemnice, dodavanje fakture ili troška poništava
      dotadašnju raspodjelu; izmjena izvora poništava raspodjelu tog izvora
    - VPC i MPC se formiraju tek kad su svi izvori raspoređeni
    - robna skladišta: marža (procenat / iznos), VPC i MPC (MPC = VPC + PDV artikla);
      postojeće cijene iz cjenovnika se samo čitaju (cjenovnik se ne mijenja)
    - zaključavanje: cijene u prijemnice, prijemnice zaključene (roba raspoloživa)
    - otključavanje: samo administrator, samo materijalna skladišta, dok roba nije izdata
  Nove kolone: KALKULACIJE (skladiste_id, status, nacin_raspodjele),
               KALKULACIJA_KUF (iznos, sa_pdv),
               KALKULACIJA_STAVKE (operacija_id, stavka_id, ulazna_cijena, osnovica, ...)
  Nova tabela: KALKULACIJA_TROSKOVI (zavisni troškovi bez fakture)
  Skripta se može pokrenuti više puta.
================================================================================
*/
