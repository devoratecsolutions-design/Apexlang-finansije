declare
    l_n number;
    procedure kolona (p_tabela in varchar2, p_ime in varchar2, p_def in varchar2) is
        l_n number;
    begin
        select count(*) into l_n from user_tab_columns where table_name = p_tabela and column_name = upper(p_ime);
        if l_n = 0 then
            execute immediate 'alter table ' || p_tabela || ' add (' || p_ime || ' ' || p_def || ')';
            dbms_output.put_line('Dodata kolona ' || p_tabela || '.' || upper(p_ime));
        end if;
    end;
    procedure indeks (p_ime in varchar2, p_ddl in varchar2) is
        l_n number;
    begin
        select count(*) into l_n from user_indexes where index_name = upper(p_ime);
        if l_n = 0 then
            execute immediate p_ddl;
        end if;
    exception
        when others then
            dbms_output.put_line('UPOZORENJE: indeks ' || upper(p_ime) || ': ' || sqlerrm);
    end;
begin
    kolona('KALKULACIJE', 'skladiste_id', 'number');
    kolona('KALKULACIJE', 'status', 'varchar2(1 char)');
    kolona('KALKULACIJE', 'nacin_raspodjele', 'varchar2(1 char)');
    kolona('KALKULACIJA_KUF', 'iznos', 'number');
    kolona('KALKULACIJA_KUF', 'sa_pdv', 'varchar2(1 char)');
    kolona('KALKULACIJA_KUF', 'nacin_raspodjele', 'varchar2(1 char)');
    for c in (select column_value as k from table(sys.odcivarchar2list(
                  'operacija_id number', 'stavka_id number', 'redni_broj number', 'ulazna_cijena number',
                  'osnovica number', 'rucni_iznos number', 'nabavna_vrijednost number', 'nabavna_cijena number',
                  'marza_procenat number', 'marza_iznos number', 'vpc number', 'pdv_stopa number', 'mpc number'))) loop
        kolona('KALKULACIJA_STAVKE', substr(c.k, 1, instr(c.k, ' ') - 1), substr(c.k, instr(c.k, ' ') + 1));
    end loop;

    select count(*) into l_n from user_tables where table_name = 'KALKULACIJA_TROSKOVI';
    if l_n = 0 then
        execute immediate q'[
            create table kalkulacija_troskovi (
                id             number generated by default on null as identity,
                kalkulacija_id number not null,
                opis           varchar2(500 char) not null,
                iznos          number not null,
                created        date default sysdate not null,
                created_by     varchar2(255 char) default coalesce(sys_context('APEX$SESSION', 'APP_USER'), user) not null,
                constraint kalkulacija_troskovi_pk primary key (id),
                constraint kalkulacija_troskovi_kalk_fk foreign key (kalkulacija_id) references kalkulacije (id)
            )]';
        dbms_output.put_line('Napravljena tabela KALKULACIJA_TROSKOVI');
    end if;

    kolona('KALKULACIJA_TROSKOVI', 'nacin_raspodjele', 'varchar2(1 char)');

    select count(*) into l_n from user_tables where table_name = 'KALKULACIJA_RASPODJELA';
    if l_n = 0 then
        execute immediate q'[
            create table kalkulacija_raspodjela (
                id                    number generated by default on null as identity,
                kalkulacija_id        number not null,
                kalkulacija_kuf_id    number,
                kalkulacija_trosak_id number,
                kalkulacija_stavka_id number not null,
                iznos                 number,
                constraint kalkulacija_raspodjela_pk primary key (id),
                constraint kalkulacija_raspodjela_kalk_fk foreign key (kalkulacija_id) references kalkulacije (id),
                constraint kalkulacija_raspodjela_izvor_ck check (
                    (kalkulacija_kuf_id is not null and kalkulacija_trosak_id is null)
                    or (kalkulacija_kuf_id is null and kalkulacija_trosak_id is not null))
            )]';
        dbms_output.put_line('Napravljena tabela KALKULACIJA_RASPODJELA');
    end if;
    indeks('KALKULACIJA_RASPODJELA_I1', 'create index kalkulacija_raspodjela_i1 on kalkulacija_raspodjela (kalkulacija_id)');
    indeks('KALKULACIJA_RASPODJELA_I2', 'create index kalkulacija_raspodjela_i2 on kalkulacija_raspodjela (kalkulacija_stavka_id)');

    indeks('KALKULACIJE_SKLADISTE_I', 'create index kalkulacije_skladiste_i on kalkulacije (skladiste_id)');
    indeks('KALKULACIJA_TROSKOVI_I1', 'create index kalkulacija_troskovi_i1 on kalkulacija_troskovi (kalkulacija_id)');
    indeks('KALKULACIJA_KUF_I_KUF', 'create index kalkulacija_kuf_i_kuf on kalkulacija_kuf (kuf_id)');
    indeks('KALKULACIJA_OPERACIJE_I_OP', 'create index kalkulacija_operacije_i_op on kalkulacija_operacije (operacija_id)');
    indeks('KALKULACIJA_STAVKE_I_OP', 'create index kalkulacija_stavke_i_op on kalkulacija_stavke (operacija_id)');

    -- postojeći podaci
    execute immediate q'[update kalkulacije set status = case when zakljucano = 'Y' then 'Z' else 'P' end where status is null]';
    execute immediate q'[update kalkulacije set nacin_raspodjele = 'V' where nacin_raspodjele is null]';
    execute immediate q'[
        update kalkulacije k
           set k.skladiste_id = (select max(o.skladiste_id) from kalkulacija_operacije ko join operacije o on o.id = ko.operacija_id
                                  where ko.kalkulacija_id = k.id)
         where k.skladiste_id is null]';
    execute immediate q'[update kalkulacija_kuf set sa_pdv = 'N' where sa_pdv is null]';
    execute immediate q'[update kalkulacija_kuf set nacin_raspodjele = 'V' where nacin_raspodjele is null]';
    execute immediate q'[update kalkulacija_troskovi set nacin_raspodjele = 'V' where nacin_raspodjele is null]';
    commit;
end;
