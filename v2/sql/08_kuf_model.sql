-- 3) vrste dokumenata i brojači za svaku firmu --------------------------------
declare
    type t_vrsta is record (sifra varchar2(10), naziv varchar2(100));
    type t_vrste is table of t_vrsta;
    l_vrste  t_vrste := t_vrste();
    l_app_id number;
    l_modul  number;
    l_id     number;
    l_n      number;
    l_nove   number := 0;
    l_broj   number := 0;
    l_prefix varchar2(64);
    l_duzina number;
    l_sufix  varchar2(64);

    procedure dodaj (p_sifra in varchar2, p_naziv in varchar2) is
    begin
        l_vrste.extend;
        l_vrste(l_vrste.last).sifra := p_sifra;
        l_vrste(l_vrste.last).naziv := p_naziv;
    end;
begin
    dodaj('UAV',  'Ulazna avansna faktura');
    dodaj('UAVZ', 'Ulazna avansna faktura - zatvaranje');
    dodaj('UKO',  'Primljeno knjižno odobrenje');
    dodaj('UKZ',  'Primljeno knjižno zaduženje');

    select id into l_modul from sif.acc_moduli where upper(sifra) = 'UF';

    for uf in (select vd.ooj_id, vd.app_id, vd.vrsta_naloga_id, vd.id
                 from sif.vrste_dokumenata vd
                where vd.acc_modul_id = l_modul
                  and upper(vd.sifra) = 'UF'
                  and vd.ooj_id is not null
                  and vd.valid = 'Y') loop
        for i in 1 .. l_vrste.count loop
            select count(*) into l_n
              from sif.vrste_dokumenata
             where ooj_id = uf.ooj_id
               and acc_modul_id = l_modul
               and upper(sifra) = l_vrste(i).sifra;
            if l_n = 0 then
                sif.acc_pkg.insert_vrste_dokumenata(
                    p_app_id          => uf.app_id,
                    p_acc_modul_id    => l_modul,
                    p_ooj_id          => uf.ooj_id,
                    p_sifra           => l_vrste(i).sifra,
                    p_naziv           => l_vrste(i).naziv,
                    p_opis            => l_vrste(i).naziv,
                    p_vrsta_naloga_id => uf.vrsta_naloga_id,
                    p_fiskalna_sifra  => null,
                    p_tip_kretanja    => null,
                    p_valid           => 'Y',
                    p_id              => l_id
                );
                l_nove := l_nove + 1;
            else
                select min(id) into l_id
                  from sif.vrste_dokumenata
                 where ooj_id = uf.ooj_id and acc_modul_id = l_modul and upper(sifra) = l_vrste(i).sifra;
            end if;

            -- brojač za svaku godinu u kojoj firma ima brojač UF (prefiks prema UF)
            for g in 2024 .. extract(year from sysdate) + 1 loop
                if core.protokoli_pkg.check_brojac(uf.ooj_id, 'uf', g)
                   and not core.protokoli_pkg.check_brojac(uf.ooj_id, l_vrste(i).sifra, g) then
                    core.protokoli_pkg.get_brojac(
                        p_ooj_id             => uf.ooj_id,
                        p_vrsta_naloga_sifra => 'uf',
                        p_godina             => g,
                        p_prefix             => l_prefix,
                        p_duzina             => l_duzina,
                        p_sufix              => l_sufix
                    );
                    core.protokoli_pkg.insert_protokol(
                        p_ooj_id          => uf.ooj_id,
                        p_vrsta_naloga_id => l_id,
                        p_godina          => g,
                        p_prefix          => case
                                                 when instr(upper(l_prefix), 'UF') > 0
                                                 then regexp_replace(l_prefix, 'UF', l_vrste(i).sifra, 1, 1, 'i')
                                                 else l_vrste(i).sifra || '-'
                                             end,
                        p_broj            => 0,
                        p_sufix           => l_sufix,
                        p_duzina          => nvl(l_duzina, 6),
                        p_auto_restart    => 'Y'
                    );
                    l_broj := l_broj + 1;
                end if;
            end loop;
        end loop;
    end loop;
    commit;
    dbms_output.put_line('Nove vrste dokumenata: ' || l_nove || ', novi brojači: ' || l_broj);
end;
/

-- 4) prenos postojećih podataka ------------------------------------------------
declare
    l_modul number;
    l_n     number;
begin
    select id into l_modul from sif.acc_moduli where upper(sifra) = 'UF';

    -- 4.1 godina iz datuma fakture
    insert into kuf_migracija_v2 (kuf_id, kolona, stara_vrijednost, nova_vrijednost)
    select id, 'GODINA', null, to_char(extract(year from datum_fakture))
      from kuf
     where godina is null and datum_fakture is not null;
    update kuf set godina = extract(year from datum_fakture)
     where godina is null and datum_fakture is not null;
    dbms_output.put_line('Popunjena godina: ' || sql%rowcount);

    -- 4.2 vrsta dokumenta
    merge into kuf k
    using (select k2.id,
                  vd.id as vrsta_id
             from kuf k2
             left join sif.acc_pdv_indikatori p on p.id = k2.pdv_indikator_id
             join sif.vrste_dokumenata vd
               on vd.ooj_id = k2.ooj_id
              and vd.acc_modul_id = l_modul
              and upper(vd.sifra) = case
                                        when p.sifra in ('N3', 'N4', 'N5') then 'UKO'
                                        when p.sifra in ('P3', 'R3') then 'UAV'
                                        else 'UF'
                                    end
            where k2.vrsta_dokumenta_id is null) s
       on (k.id = s.id)
     when matched then update set k.vrsta_dokumenta_id = s.vrsta_id;
    l_n := sql%rowcount;
    insert into kuf_migracija_v2 (kuf_id, kolona, stara_vrijednost, nova_vrijednost)
    select k.id, 'VRSTA_DOKUMENTA_ID', null, to_char(k.vrsta_dokumenta_id)
      from kuf k
     where k.vrsta_dokumenta_id is not null
       and not exists (select 1 from kuf_migracija_v2 m where m.kuf_id = k.id and m.kolona = 'VRSTA_DOKUMENTA_ID');
    dbms_output.put_line('Postavljena vrsta dokumenta: ' || l_n);

    -- 4.3 PDV specifikacija se NE prenosi ovdje: dok faktura nema svoje redove,
    --     VW_KUF_PDV_SPEC ih izvodi iz zaglavlja (pa postojeća forma i knjiženje
    --     rade kao i do sada); redovi se prave kad se faktura otvori u novoj formi
    --     (KUF_PKG.pripremi_specifikaciju).

    -- 4.4 dokumenti (kopija; kolone u KUF ostaju dok se ne provjeri)
    insert into kuf_dokumenti (kuf_id, dokument, naziv, mime_tip, velicina, created)
    select k.id, k.document, k.document_filename, k.document_mimetype,
           dbms_lob.getlength(k.document), nvl(k.document_lastupd, k.created)
      from kuf k
     where k.document is not null
       and not exists (select 1 from kuf_dokumenti d where d.kuf_id = k.id);
    dbms_output.put_line('Kopirani dokumenti: ' || sql%rowcount);

    commit;
end;
/

-- 5) PDV specifikacija za svaku fakturu --------------------------------------
-- Redovi iz KUF_PDV; storno dokument bez svojih redova -> redovi originala sa
-- suprotnim predznakom; ostale fakture bez redova -> jedan red iz zaglavlja.
create or replace force view vw_kuf_pdv_spec as
with r as (
    select p.kuf_id, p.id as red_id, p.redni_broj, p.pdv_indikator_id,
           p.osnovica, p.pdv, p.valuta_osnovica, p.valuta_pdv, 'R' as izvor, p.izvor_red_id
      from kuf_pdv p
    union all
    select k.id, null, o.redni_broj, o.pdv_indikator_id,
           -o.osnovica, -o.pdv, -o.valuta_osnovica, -o.valuta_pdv, 'S', null
      from kuf k
      join kuf_pdv o on o.kuf_id = k.storniran_id
     where k.storniran_id is not null
       and not exists (select 1 from kuf_pdv x where x.kuf_id = k.id)
    union all
    select k.id, null, 1, k.pdv_indikator_id,
           k.iznos_bez_pdv, nvl(k.iznos_sa_pdv, 0) - nvl(k.iznos_bez_pdv, 0),
           k.valuta_iznos_bez_pdv, nvl(k.valuta_iznos_sa_pdv, 0) - nvl(k.valuta_iznos_bez_pdv, 0), 'Z', null
      from kuf k
     where not exists (select 1 from kuf_pdv x where x.kuf_id = k.id)
       and not (k.storniran_id is not null
                and exists (select 1 from kuf_pdv o where o.kuf_id = k.storniran_id))
)
select r.kuf_id,
       r.red_id,
       r.redni_broj,
       r.izvor,
       r.izvor_red_id,
       r.pdv_indikator_id,
       i.sifra            as pdv_indikator_sifra,
       i.naziv            as pdv_indikator_naziv,
       i.vrijednost       as stopa,
       i.polje_osnovice,
       i.polje_pdv,
       i.polje_kp,
       i.pravo_na_odbitak,
       i.pdv_dobavljacu,
       i.vrsta            as pdv_vrsta,
       r.osnovica,
       r.pdv,
       r.valuta_osnovica,
       r.valuta_pdv,
       -- iznos sa fakture dobavljača: kod obrnute naplate i uvoza (PDV_DOBAVLJACU = N)
       -- PDV nije na fakturi dobavljača, pa se ne dodaje (postoji samo za UIO)
       nvl(r.osnovica, 0) + case when i.pdv_dobavljacu = 'N' then 0 else nvl(r.pdv, 0) end as iznos_sa_pdv,
       nvl(r.valuta_osnovica, 0) + case when i.pdv_dobavljacu = 'N' then 0 else nvl(r.valuta_pdv, 0) end as valuta_iznos_sa_pdv
  from r
  left join sif.acc_pdv_indikatori i on i.id = r.pdv_indikator_id;

comment on table vw_kuf_pdv_spec is 'PDV specifikacija svake ulazne fakture (KUF_PDV, storno original, ili zaglavlje) - v2';

